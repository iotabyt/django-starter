from django import template
from django.utils.html import format_html

register = template.Library()


@register.filter
def initials(user) -> str:
    """Up to two initials from the user's name, or the first letter of their email."""
    name = (getattr(user, "name", "") or "").strip()
    if name:
        parts = name.split()
        return (parts[0][0] + (parts[-1][0] if len(parts) > 1 else "")).upper()
    email = getattr(user, "email", "") or "?"
    return email[:1].upper()


@register.filter
def startswith(value, prefix) -> bool:
    """`request.path|startswith:some_url` in an if tag, to highlight the current nav item."""
    return bool(prefix) and str(value).startswith(str(prefix))


